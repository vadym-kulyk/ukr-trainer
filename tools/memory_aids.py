PALETTE = ["var(--lime)", "var(--violet)", "var(--yellow)", "var(--wrong)", "var(--right)", "var(--violet)"]
OPS = ["+", "=", "→", "↔"]


def leafs(items):
    return "".join(f"<li>{x}</li>" for x in items)


def mindmap(core, branches):
    half = (len(branches) + 1) // 2
    def col(part, offset):
        return "".join(f'<div class="mm-b" style="--c:{PALETTE[(i + offset) % len(PALETTE)]}"><b>{lab}</b><ul>{leafs(items)}</ul></div>'
                       for i, (lab, items) in enumerate(part))
    return (f'<div class="mmap" data-mm><div class="mm-head"><b>Ментальна карта</b>'
            f'<button class="btn small ghost" type="button" data-mmq>Перевір себе</button></div>'
            f'<div class="mm"><div class="mm-core">{core}</div>'
            f'<div class="mm-l">{col(branches[:half], 0)}</div><div class="mm-r">{col(branches[half:], half)}</div></div>'
            f'<p class="mm-tip">Натисніть «Перевір себе»: приклади сховаються. Згадайте кожну гілку, потім торкніться її, щоб перевірити.</p></div>')


def frow(row):
    expr, _, ex = row.partition(" | ")
    toks = re.split(r"\s+(\+|=|→|↔)\s+", expr)
    out, last_op = [], None
    for i, t in enumerate(toks):
        if t in OPS:
            out.append(f"<i>{t}</i>"); last_op = t; continue
        res = i == len(toks) - 1 and last_op in ("=", "→")
        out.append(f'<span class="fx{" res" if res else ""}">{t}</span>')
    return f'<div class="frow">{"".join(out)}{f"<em>{ex}</em>" if ex else ""}</div>'


def scheme(rows, mnemos):
    h = '<h3>Схеми для запам’ятовування</h3><div class="fscheme"><b>Формула правила</b>' + "".join(frow(r) for r in rows) + "</div>"
    for title, say, expl in mnemos:
        h += f'<div class="mnemo"><b>{title}</b><span class="say">{say}</span><span>{expl}</span></div>'
    return h


def put(s, tag, block, anchor_fn):
    pat = re.compile(rf"<!--{tag}-->.*?<!--/{tag}-->\n?", re.S)
    s = pat.sub("", s)
    i = anchor_fn(s)
    return s[:i] + f"<!--{tag}-->{block}<!--/{tag}-->\n" + s[i:]


def after_intro(s):
    m = re.match(r"\s*<p[^>]*>.*?</p>\s*", s, re.S)
    return m.end() if m else 0


def before_quiz(s):
    for k in ('<div class="quiz">', '<p class="note">Джерела'):
        i = s.find(k)
        if i >= 0:
            return i
    return len(s)


def main():
    done = 0
    for tid, d in A.items():
        p = ROOT / f"{tid}.html"
        s = p.read_text(encoding="utf-8")
        s = put(s, "mm", mindmap(*d["map"]), after_intro)
        s = put(s, "ms", scheme(d["f"], d.get("m", [])), before_quiz)
        p.write_text(s, encoding="utf-8")
        done += 1
    missing = sorted(x.stem for x in ROOT.glob("*.html") if x.stem not in A)
    print("updated", done, "pages; without aids:", missing or "none")


if __name__ == "__main__":
    main()
