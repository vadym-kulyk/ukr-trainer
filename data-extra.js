<p>Приголосні змінюються, коли від основ на [к], [ч], [ц], [г], [ж], [з], [х], [ш], [с΄] творимо прикметники із суфіксом <b>-ськ-</b> та іменники із суфіксом <b>-ств-</b>.</p>
